import { v4 as uuidv4 } from 'uuid'
import type { ApiCollection, ApiFolder, ApiRequest, KeyValuePair, RequestAuth, RequestBody } from '../../types/api-studio'
import type { AuthScheme, DetectedEndpoint } from '../../types/code-scanner'
import { pathParamNames, toColonParams } from './paths'
import { groupEndpoints, hasAuthSegment } from './group'
import { validationCases, validationTestScript } from './validation-tests'
import { endpointKey, requestStructure } from './fingerprint'

export const BASE_URL_VARIABLE = 'baseUrl'
export const AUTH_TOKEN_VARIABLE = 'authToken'
export const API_KEY_VARIABLE = 'apiKey'

/** Collection auth for a scheme, and the environment variables it references. */
function collectionAuth(scheme: AuthScheme, useVariables: boolean): { auth: RequestAuth; variables: string[] } {
  const v = (name: string) => (useVariables ? `{{${name}}}` : '')
  switch (scheme.type) {
    case 'apiKey':
      return {
        auth: { type: 'apiKey', apiKeyName: scheme.name, apiKeyValue: v(API_KEY_VARIABLE), apiKeyLocation: scheme.in },
        variables: [API_KEY_VARIABLE]
      }
    case 'basic':
      return { auth: { type: 'basic', basicUsername: v('username'), basicPassword: v('password') }, variables: ['username', 'password'] }
    default:
      // `Authorization: Token <jwt>` (DRF, RealWorld) isn't Bearer: send the header as-is.
      return scheme.prefix && scheme.prefix !== 'Bearer'
        ? {
            auth: { type: 'apiKey', apiKeyName: 'Authorization', apiKeyValue: `${scheme.prefix} ${v(AUTH_TOKEN_VARIABLE)}`.trim(), apiKeyLocation: 'header' },
            variables: [AUTH_TOKEN_VARIABLE]
          }
        : { auth: { type: 'bearer', bearerToken: v(AUTH_TOKEN_VARIABLE) }, variables: [AUTH_TOKEN_VARIABLE] }
  }
}

export interface BuildCollectionOptions {
  name: string
  /** Value for the `{{baseUrl}}` variable every request starts with. */
  baseUrl: string
  /**
   * `true` (default): requests use `{{baseUrl}}` / `{{authToken}}`, filled by an environment.
   * `false`: the base URL is written into each request, for imports without an environment.
   */
  useVariables?: boolean
  /** How protected endpoints expect credentials (default: Bearer token). */
  auth?: AuthScheme
  /** Scanned folder; recorded on the collection so a later scan can update it. */
  rootPath?: string
  /** Add a `Validation tests` folder: requests that break one body rule each and expect a 4xx. */
  validationTests?: boolean
  description?: string
  now?: string
}

export const VALIDATION_FOLDER = 'Validation tests'

/** Paths a login response commonly puts its token at. */
const TOKEN_PATHS = [
  'token',
  'accessToken',
  'access_token',
  'jwt',
  'idToken',
  'id_token',
  'data.token',
  'data.accessToken',
  'data.access_token',
  'user.token',
  'data.user.token',
  'tokens.access',
  'tokens.accessToken',
  'tokens.access.token',
  'auth.token',
  'result.token'
]

/** Sign-in routes whose response carries the token the rest of the API needs. */
export function isLoginEndpoint(endpoint: DetectedEndpoint): boolean {
  if (endpoint.method !== 'POST' || endpoint.host || endpoint.graphql || !hasAuthSegment(endpoint.path)) return false
  const last = endpoint.path.split('/').filter((s) => s && !s.startsWith(':') && !s.startsWith('{')).at(-1) ?? ''
  return /^(login|log-in|signin|sign-in|sign_in|token|access-token|access_token|authenticate|session|sessions)$/i.test(last)
}

/** Test script that saves a login's token as `{{authToken}}`, so the protected requests work right after. */
export function loginTokenScript(variable = AUTH_TOKEN_VARIABLE): string {
  return `// Generated by the Code Scanner: saves the token this login returns for the other requests.
var body = null
try { body = pm.response.json() } catch (e) {}
var paths = ${JSON.stringify(TOKEN_PATHS)}
var token = null
for (var i = 0; i < paths.length && !token; i++) {
  var value = paths[i].split('.').reduce(function (o, k) { return o && typeof o === 'object' ? o[k] : undefined }, body)
  if (typeof value === 'string' && value) token = value
}
if (!token) {
  for (var name in pm.response.headers) {
    if (name.toLowerCase() === 'authorization') token = String(pm.response.headers[name]).replace(/^(Bearer|Token|JWT)\\s+/i, '')
  }
}
pm.test("login returns a token", function () {
  if (pm.response.status >= 400) throw new Error("Login failed with " + pm.response.status + ": check the credentials in the body")
  if (!token) throw new Error("No token found in the response: set {{${variable}}} in the environment by hand")
})
if (token) pm.environment.set("${variable}", token)
`
}

export interface ScannedCollection {
  collection: ApiCollection
  /** Variables the requests reference; the caller decides whether to create an environment. */
  environmentVariables: Array<{ key: string; value: string }>
}

const BODY_METHODS = new Set(['POST', 'PUT', 'PATCH'])

function keyValue(key: string, value = '', enabled = true, description?: string): KeyValuePair {
  return { id: uuidv4(), key, value, enabled, ...(description ? { description } : {}) }
}

function requestName(endpoint: DetectedEndpoint): string {
  if (endpoint.graphql) return endpoint.graphql.operationName ?? 'GraphQL operation'
  if (endpoint.summary?.trim()) return endpoint.summary.trim()
  return `${endpoint.method} ${endpoint.path}`
}

function requestBody(endpoint: DetectedEndpoint): RequestBody {
  const example = endpoint.requestBody?.example
  if (example === undefined && !BODY_METHODS.has(endpoint.method)) return { type: 'none', content: '' }
  const types = endpoint.requestBody?.contentTypes ?? []
  const isJson = types.length === 0 || types.some((ct) => ct.includes('json'))
  if (!isJson && types.some((ct) => ct.includes('x-www-form-urlencoded')) && example && typeof example === 'object') {
    // API Studio stores url-encoded bodies as `key=value` lines.
    const lines = Object.entries(example as Record<string, unknown>).map(([k, v]) => `${k}=${typeof v === 'object' ? JSON.stringify(v) : String(v ?? '')}`)
    return { type: 'x-www-form-urlencoded', content: lines.join('\n') }
  }
  if (!isJson) return { type: 'text', content: typeof example === 'string' ? example : '' }
  return { type: 'json', content: JSON.stringify(example ?? {}, null, 2) }
}

function requestDescription(endpoint: DetectedEndpoint): string {
  const lines: string[] = []
  if (endpoint.description) lines.push(endpoint.description)
  if (endpoint.responseExample !== undefined) {
    const status = endpoint.responses[0]?.status ?? '200'
    lines.push(`Example response (${status}):\n\n\`\`\`json\n${JSON.stringify(endpoint.responseExample, null, 2)}\n\`\`\``)
  }
  const callers = new Set((endpoint.callers ?? []).map((s) => `${s.file}:${s.line}`))
  const sources = endpoint.sources.map((s) => `${s.file}:${s.line}`).filter((s) => !callers.has(s)).join(', ')
  if (sources) lines.push(`Detected in ${sources}`)
  if (callers.size) lines.push(`Called from ${[...callers].join(', ')}`)
  return lines.join('\n\n')
}

function toRequest(endpoint: DetectedEndpoint, folderId: string | null, collectionHasAuth: boolean, baseOrigin: string, now: string): ApiRequest {
  const path = toColonParams(endpoint.path)
  const queryParams = endpoint.parameters
    .filter((p) => p.in === 'query')
    .map((p) => keyValue(p.name, p.example ?? '', p.required, p.description))
  const headers = endpoint.parameters
    .filter((p) => p.in === 'header')
    .map((p) => keyValue(p.name, p.example ?? '', p.required, p.description))
  // Third-party APIs keep their own host; everything else is relative to {{baseUrl}}.
  const origin = endpoint.host ?? baseOrigin
  const graphql = endpoint.graphql
  return {
    id: uuidv4(),
    name: requestName(endpoint),
    method: endpoint.method,
    url: `${origin}${path === '/' ? '' : path}`,
    headers,
    queryParams,
    pathParams: pathParamNames(path).map((name) => keyValue(name)),
    body: graphql ? { type: 'none', content: '' } : requestBody(endpoint),
    // Protected endpoints use the collection's bearer token; public ones (and third parties) send nothing.
    auth: !endpoint.host && (endpoint.securityRequired || !collectionHasAuth) ? { type: 'inherit' } : { type: 'none' },
    tests: '',
    preRequestScript: '',
    description: requestDescription(endpoint),
    requestType: graphql ? 'graphql' : 'http',
    ...(graphql
      ? {
          graphql: { query: graphql.query, variables: '{\n}', ...(graphql.operationName ? { operationName: graphql.operationName } : {}) },
          headers: [...headers, keyValue('Content-Type', 'application/json')]
        }
      : {}),
    folderId,
    timeoutMs: 30_000,
    updatedAt: now
  }
}

/** Where the route is defined, not where the frontend calls it. */
function definitionSites(endpoint: DetectedEndpoint): Array<{ file: string; line: number }> {
  const callers = new Set((endpoint.callers ?? []).map((c) => `${c.file}:${c.line}`))
  const own = endpoint.sources.filter((s) => !callers.has(`${s.file}:${s.line}`))
  return (own.length ? own : endpoint.sources).slice(0, 3).map(({ file, line }) => ({ file, line }))
}

/** Builds a ready-to-send collection: one request per endpoint, grouped into folders by resource. */
export function buildCollectionFromEndpoints(
  endpoints: DetectedEndpoint[],
  options: BuildCollectionOptions
): ScannedCollection {
  const now = options.now ?? new Date().toISOString()
  const useVariables = options.useVariables ?? true
  const hasProtectedEndpoint = endpoints.some((e) => e.securityRequired && !e.host)
  const protectedAuth = hasProtectedEndpoint ? collectionAuth(options.auth ?? { type: 'bearer' }, useVariables) : null
  const baseOrigin = useVariables ? `{{${BASE_URL_VARIABLE}}}` : options.baseUrl.trim().replace(/\/+$/, '')

  // `/user/:id`, `/users` and an OpenAPI `Users` tag land in one folder; sign-in comes first so a
  // collection run logs in before it calls protected routes.
  const groups = groupEndpoints(endpoints).sort((a, b) => Number(b.key === 'auth') - Number(a.key === 'auth'))
  const cases = options.validationTests ? new Map(endpoints.map((e) => [e.id, validationCases(e)])) : new Map()
  const hasValidation = [...cases.values()].some((list) => list.length > 0)
  const useFolders = groups.length > 1 || hasValidation
  // The login script fills `{{authToken}}`; API keys and Basic credentials are typed in by hand.
  const savesToken = Boolean(protectedAuth) && useVariables && protectedAuth!.variables.includes(AUTH_TOKEN_VARIABLE)

  const folders: ApiFolder[] = []
  const folderIds = new Map<string, string>()
  /** Folder for a path of names (`['users', 'posts']`), created on first use. */
  const folderAt = (path: string[]): string | null => {
    let parentId: string | null = null
    for (let i = 0; i < path.length; i++) {
      const key = path.slice(0, i + 1).join('\u0000')
      let id = folderIds.get(key)
      if (!id) {
        id = uuidv4()
        folderIds.set(key, id)
        folders.push({ id, name: path[i], parentId, auth: { type: 'inherit' } })
      }
      parentId = id
    }
    return parentId
  }

  const requests: ApiRequest[] = []
  const validation: ApiRequest[] = []
  for (const group of groups) {
    const subfolderOf = new Map(group.subgroups.flatMap((sub) => sub.endpoints.map((e) => [e.id, sub.name])))
    const ordered = group.key === 'auth' ? [...group.endpoints].sort((a, b) => Number(isLoginEndpoint(b)) - Number(isLoginEndpoint(a))) : group.endpoints
    for (const endpoint of ordered) {
      const sub = subfolderOf.get(endpoint.id)
      const folderId = useFolders ? folderAt(sub ? [group.name, sub] : [group.name]) : null
      const request = toRequest(endpoint, folderId, Boolean(protectedAuth), baseOrigin, now)
      if (savesToken && isLoginEndpoint(endpoint)) {
        request.tests = loginTokenScript()
        request.description = [request.description, 'Sending this request saves the returned token as {{authToken}} for the protected requests.']
          .filter(Boolean)
          .join('\n\n')
      }
      request.scan = { key: endpointKey(endpoint), structure: requestStructure(request), sources: definitionSites(endpoint) }
      requests.push(request)

      for (const item of cases.get(endpoint.id) ?? []) {
        const base = toRequest(endpoint, folderAt([VALIDATION_FOLDER, group.name]), Boolean(protectedAuth), baseOrigin, now)
        const test: ApiRequest = {
          ...base,
          name: `${endpoint.method} ${endpoint.path} · ${item.label}`,
          body: { type: 'json', content: JSON.stringify(item.body, null, 2) },
          tests: validationTestScript(item.label),
          description: `Breaks one rule of the request body (${item.label}) and expects the API to reject it with a 4xx.\n\n${base.description ?? ''}`.trim()
        }
        test.scan = { key: `${endpointKey(endpoint)}#validation:${item.id}`, structure: requestStructure(test) }
        validation.push(test)
      }
    }
  }
  requests.push(...validation)

  const collection: ApiCollection = {
    id: uuidv4(),
    name: options.name.trim() || 'Scanned API',
    description: options.description ?? '',
    folders,
    requests,
    auth: protectedAuth ? protectedAuth.auth : { type: 'none' },
    headers: [],
    preRequestScript: '',
    ...(options.rootPath ? { source: { kind: 'code-scanner' as const, rootPath: options.rootPath, scannedAt: now } } : {}),
    createdAt: now,
    updatedAt: now
  }

  return {
    collection,
    environmentVariables: [
      { key: BASE_URL_VARIABLE, value: options.baseUrl.replace(/\/+$/, '') },
      ...(protectedAuth ? protectedAuth.variables.map((key) => ({ key, value: '' })) : [])
    ]
  }
}
