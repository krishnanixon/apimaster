import { v4 as uuidv4 } from 'uuid'
import type { ApiCollection } from '@shared/types/api-studio'
import type { AuthScheme, DetectedEndpoint } from '@shared/types/code-scanner'
import type { MockHttpMethod } from '@shared/types/mock-server'
import { buildCollectionFromEndpoints, type ScannedCollection } from '@shared/lib/code-scanner/spec-to-collection'
import { applyMerge, planMerge, type MergeOutcome, type MergePlan } from '@shared/lib/code-scanner/merge-collection'
import { exportableEndpoints, scanToOpenApi } from '@shared/lib/code-scanner/to-openapi'
import { endpointKey } from '@shared/lib/code-scanner/fingerprint'
import { useApiStudioStore } from '@/modules/api-studio/stores/apiStudioStore'

export interface ImportScanOptions {
  name: string
  baseUrl: string
  rootPath: string
  createEnvironment: boolean
  /** Add requests that break one body rule each and expect a 4xx (see `validation-tests.ts`). */
  validationTests?: boolean
  auth?: AuthScheme
}

export interface EnvironmentUse {
  name: string
  reused: boolean
}

export interface ImportScanResult {
  collectionId: string
  requests: number
  /** Environment made active for `{{baseUrl}}`; `reused` when an existing one was updated. */
  environment?: EnvironmentUse
}

function build(endpoints: DetectedEndpoint[], options: ImportScanOptions): ScannedCollection {
  return buildCollectionFromEndpoints(endpoints, {
    name: options.name,
    baseUrl: options.baseUrl,
    useVariables: options.createEnvironment,
    auth: options.auth,
    rootPath: options.rootPath,
    validationTests: options.validationTests,
    description: `Generated by Code Scanner from ${options.rootPath}`
  })
}

/**
 * Creates or updates the `<collection> (local)` environment and makes it active. The scan decides
 * the base URL; values you already entered (tokens, keys) are kept.
 */
function activateEnvironment(collectionName: string, variables: ScannedCollection['environmentVariables']): EnvironmentUse {
  const store = useApiStudioStore.getState()
  const name = `${collectionName} (local)`
  const existing = store.environments.find((e) => e.name === name)
  const environment = existing ?? store.createEnvironment(name)
  const current = new Map((existing?.variables ?? []).map((v) => [v.key, v]))
  const updated = variables.map((v) => {
    const kept = current.get(v.key)
    const value = v.key === 'baseUrl' || !kept?.value ? v.value : kept.value
    return { id: kept?.id ?? uuidv4(), key: v.key, value, enabled: true }
  })
  const others = (existing?.variables ?? []).filter((v) => !variables.some((n) => n.key === v.key))
  store.updateEnvironmentVariables(environment.id, [...updated, ...others])
  store.setActiveEnvironment(environment.id)
  return { name, reused: Boolean(existing) }
}

/**
 * Adds the selected endpoints to API Studio as a collection. With `createEnvironment`, requests use
 * `{{baseUrl}}`/credential variables from an environment; without it, the base URL is written into
 * each request.
 */
export function importScannedEndpoints(endpoints: DetectedEndpoint[], options: ImportScanOptions): ImportScanResult {
  const { collection, environmentVariables } = build(endpoints, options)
  useApiStudioStore.getState().addCollection(collection)
  const requests = collection.requests.length
  if (!options.createEnvironment) return { collectionId: collection.id, requests }
  return { collectionId: collection.id, requests, environment: activateEnvironment(collection.name, environmentVariables) }
}

/** Collections the scanner created (only those carry the tags a re-scan needs), newest first. */
export function scannedCollections(collections: ApiCollection[]): ApiCollection[] {
  return collections
    .filter((c) => c.source?.kind === 'code-scanner')
    .sort((a, b) => (b.source?.scannedAt ?? '').localeCompare(a.source?.scannedAt ?? ''))
}

export interface ScanMerge {
  collection: ApiCollection
  generated: ScannedCollection
  plan: MergePlan
}

/** What a re-scan would change in `collectionId`. All scanned endpoints count, so "removed" is accurate. */
export function planScanMerge(collectionId: string, endpoints: DetectedEndpoint[], options: ImportScanOptions): ScanMerge | null {
  const collection = useApiStudioStore.getState().collections.find((c) => c.id === collectionId)
  if (!collection) return null
  const generated = build(endpoints, { ...options, name: collection.name })
  const plan = planMerge(collection, generated.collection)
  // Validation tests switched off for this scan aren't "removed from the code"; leave them alone.
  if (!options.validationTests) plan.items = plan.items.filter((i) => !(i.status === 'removed' && i.key.includes('#validation:')))
  return { collection, generated, plan }
}

export function applyScanMerge(
  merge: ScanMerge,
  accepted: Set<string>,
  options: ImportScanOptions
): MergeOutcome & { environment?: EnvironmentUse } {
  const outcome = applyMerge(merge.collection, merge.generated.collection, merge.plan, accepted)
  useApiStudioStore.getState().replaceCollection(outcome.collection)
  const environment = options.createEnvironment ? activateEnvironment(merge.collection.name, merge.generated.environmentVariables) : undefined
  return { ...outcome, environment }
}

/** Default merge choices: safe updates, plus new endpoints that are selected in the scan list. */
export function defaultAccepted(plan: MergePlan, selected: DetectedEndpoint[]): Set<string> {
  const keys = new Set(selected.map(endpointKey))
  return new Set(plan.items.filter((i) => i.status === 'updated' || (i.status === 'added' && keys.has(i.key))).map((i) => i.key))
}

export function openApiDocument(endpoints: DetectedEndpoint[], title: string, baseUrl: string, auth?: AuthScheme): string {
  return JSON.stringify(scanToOpenApi({ title, baseUrl, auth, endpoints }), null, 2)
}

/** Saves an OpenAPI document; resolves to the file path, or null when the user cancels the dialog. */
export async function exportOpenApi(endpoints: DetectedEndpoint[], title: string, baseUrl: string, auth?: AuthScheme): Promise<string | null> {
  if (exportableEndpoints(endpoints).length === 0) throw new Error('No REST endpoints in the selection to export')
  const response = await window.electronAPI.apiStudio.exportCollection({
    defaultName: `${title.replace(/[^\w.-]+/g, '-') || 'api'}.openapi.json`,
    content: openApiDocument(endpoints, title, baseUrl, auth),
    title: 'Export OpenAPI document',
    filters: [{ name: 'OpenAPI JSON', extensions: ['json'] }]
  })
  if (!response.success) {
    if (/cancelled/i.test(response.error ?? '')) return null
    throw new Error(response.error ?? 'Export failed')
  }
  return response.data ?? null
}

/** New mock server with one route per endpoint; AI example responses become the route's response. */
export async function createMockServer(endpoints: DetectedEndpoint[], name: string): Promise<{ routes: number }> {
  const routes = exportableEndpoints(endpoints)
  if (routes.length === 0) throw new Error('No REST endpoints in the selection to mock')
  const response = await window.electronAPI.mockServer.importCollection({
    collectionId: 'code-scanner',
    collectionName: name,
    createNewServer: true,
    serverName: `${name} Mock`,
    requests: routes.map((e) => ({
      id: e.id,
      method: e.method as MockHttpMethod,
      url: e.path,
      name: e.summary ?? `${e.method} ${e.path}`,
      description: e.description,
      ...(e.responseExample !== undefined
        ? { exampleBody: JSON.stringify(e.responseExample, null, 2), exampleStatus: Number(e.responses[0]?.status) || undefined }
        : {})
    }))
  })
  if (!response.success) throw new Error(response.error ?? 'Could not create the mock server')
  return { routes: routes.length }
}

/** Sends the scan to AI Engineer as an OpenAPI analysis; AI Engineer's own AI consent setting still applies. */
export async function analyzeInAiEngineer(endpoints: DetectedEndpoint[], title: string, baseUrl: string, auth?: AuthScheme): Promise<void> {
  if (exportableEndpoints(endpoints).length === 0) throw new Error('No REST endpoints in the selection to test')
  const response = await window.electronAPI.aiEngineer.analyze({ openApiJson: openApiDocument(endpoints, title, baseUrl, auth) })
  if (!response.success) throw new Error(response.error ?? 'AI Engineer could not analyze the scan')
}
